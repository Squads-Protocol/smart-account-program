#!/usr/bin/env node
/**
 * Test script to verify byte-level compatibility between:
 * - Manual beet serializers (in types.ts)
 * - Generated beet serializers (in generated/types/)
 *
 * Run: node scripts/test-smallvec-compat.js
 */

const { PublicKey } = require("@solana/web3.js");

// Import from the built library
const lib = require("../lib/index.js");

// Manual implementations from types namespace
const {
  compiledMsInstructionBeet,
  messageAddressTableLookupBeet,
  transactionMessageBeet,
} = lib.types;

// Generated implementations from generated namespace
const {
  compiledInstructionBeet,
  messageAddressTableLookupBeet: generatedMessageAddressTableLookupBeet,
  transactionMessageBeet: generatedTransactionMessageBeet,
} = lib.generated;

function arraysEqual(a, b) {
  if (a.length !== b.length) return false;
  for (let i = 0; i < a.length; i++) {
    if (a[i] !== b[i]) return false;
  }
  return true;
}

function testCompiledInstruction() {
  console.log("\n=== Testing CompiledInstruction ===");

  const testData = {
    programIdIndex: 5,
    accountIndexes: [0, 1, 2, 3],
    data: [10, 20, 30, 40, 50],
  };

  const [manualBytes] = compiledMsInstructionBeet.serialize(testData);
  const [generatedBytes] = compiledInstructionBeet.serialize(testData);

  console.log("Test data:", JSON.stringify(testData));
  console.log("Manual bytes:   ", Array.from(manualBytes).join(", "));
  console.log("Generated bytes:", Array.from(generatedBytes).join(", "));

  if (arraysEqual(Array.from(manualBytes), Array.from(generatedBytes))) {
    console.log("✅ PASS: Bytes match!");
    return true;
  } else {
    console.log("❌ FAIL: Bytes differ!");
    return false;
  }
}

function testMessageAddressTableLookup() {
  console.log("\n=== Testing MessageAddressTableLookup ===");

  const testData = {
    accountKey: new PublicKey("11111111111111111111111111111111"),
    writableIndexes: [0, 1, 2],
    readonlyIndexes: [3, 4],
  };

  const [manualBytes] = messageAddressTableLookupBeet.serialize(testData);
  const [generatedBytes] =
    generatedMessageAddressTableLookupBeet.serialize(testData);

  console.log("Test data:", {
    accountKey: testData.accountKey.toBase58(),
    writableIndexes: testData.writableIndexes,
    readonlyIndexes: testData.readonlyIndexes,
  });
  console.log("Manual bytes:   ", Array.from(manualBytes).join(", "));
  console.log("Generated bytes:", Array.from(generatedBytes).join(", "));

  if (arraysEqual(Array.from(manualBytes), Array.from(generatedBytes))) {
    console.log("✅ PASS: Bytes match!");
    return true;
  } else {
    console.log("❌ FAIL: Bytes differ!");
    return false;
  }
}

function testTransactionMessage() {
  console.log("\n=== Testing TransactionMessage ===");

  // Use valid base58 pubkeys (System Program and Token Program)
  const systemProgram = new PublicKey("11111111111111111111111111111111");
  const tokenProgram = new PublicKey("TokenkegQfeZyiNwAJbNbGKPFXCWuBvf9Ss623VQ5DA");
  const lookupTable = new PublicKey("AddressLookupTab1e1111111111111111111111111");

  const testData = {
    numSigners: 2,
    numWritableSigners: 1,
    numWritableNonSigners: 3,
    accountKeys: [systemProgram, tokenProgram],
    instructions: [
      {
        programIdIndex: 1,
        accountIndexes: [0],
        data: [1, 2, 3],
      },
    ],
    addressTableLookups: [
      {
        accountKey: lookupTable,
        writableIndexes: [0],
        readonlyIndexes: [1, 2],
      },
    ],
  };

  const [manualBytes] = transactionMessageBeet.serialize(testData);
  const [generatedBytes] = generatedTransactionMessageBeet.serialize(testData);

  console.log("Test data: (TransactionMessage with 2 keys, 1 ix, 1 lookup)");
  console.log("Manual bytes length:   ", manualBytes.length);
  console.log("Generated bytes length:", generatedBytes.length);
  console.log("Manual bytes:   ", Array.from(manualBytes).slice(0, 50).join(", "), "...");
  console.log("Generated bytes:", Array.from(generatedBytes).slice(0, 50).join(", "), "...");

  if (arraysEqual(Array.from(manualBytes), Array.from(generatedBytes))) {
    console.log("✅ PASS: Bytes match!");
    return true;
  } else {
    console.log("❌ FAIL: Bytes differ!");
    // Show where they differ
    for (let i = 0; i < Math.max(manualBytes.length, generatedBytes.length); i++) {
      if (manualBytes[i] !== generatedBytes[i]) {
        console.log(`   First difference at index ${i}: manual=${manualBytes[i]}, generated=${generatedBytes[i]}`);
        break;
      }
    }
    return false;
  }
}

function main() {
  console.log("Testing SmallVec serialization compatibility...");
  console.log("Comparing manual implementations (types.ts) vs generated (fix-smallvec.js processed)");

  let allPassed = true;

  allPassed = testCompiledInstruction() && allPassed;
  allPassed = testMessageAddressTableLookup() && allPassed;
  allPassed = testTransactionMessage() && allPassed;

  console.log("\n" + "=".repeat(50));
  if (allPassed) {
    console.log("✅ All tests passed! Generated types are byte-compatible.");
    process.exit(0);
  } else {
    console.log("❌ Some tests failed! Check output above.");
    process.exit(1);
  }
}

main();
